//go:build sqlite_fts5

package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// paritySchemaPath is the messages.db schema the parity harness builds its
// test database from (see parity/README.md). It must be exactly what the
// bridge creates, so the harness tests the MCP server against a real schema.
// Regenerate it with:  PARITY_UPDATE=1 go test -tags sqlite_fts5 -run TestParitySchema .
var paritySchemaPath = filepath.Join("..", "parity", "fixture", "schema.sql")

func TestParitySchemaMatchesBridge(t *testing.T) {
	schemaFile, err := filepath.Abs(paritySchemaPath)
	if err != nil {
		t.Fatal(err)
	}
	t.Chdir(t.TempDir())

	store, err := NewMessageStore()
	if err != nil {
		t.Fatalf("NewMessageStore: %v", err)
	}
	defer store.Close()

	// In creation order. FTS5 creates its own shadow tables
	// (messages_fts_data and so on) and SQLite its own indexes; neither can
	// be created by hand, so both are left out.
	rows, err := store.db.Query(`
		SELECT sql FROM sqlite_master
		WHERE sql IS NOT NULL AND name NOT LIKE 'messages_fts_%'
		ORDER BY rowid`)
	if err != nil {
		t.Fatal(err)
	}
	defer rows.Close()
	var statements []string
	for rows.Next() {
		var sql string
		if err := rows.Scan(&sql); err != nil {
			t.Fatal(err)
		}
		statements = append(statements, sql+";")
	}
	if err := rows.Err(); err != nil {
		t.Fatal(err)
	}

	header := "-- messages.db schema as created by the bridge (whatsapp-bridge/main.go).\n" +
		"-- Generated by TestParitySchemaMatchesBridge; do not edit by hand.\n" +
		"-- Statements are separated by blank lines.\n\n"
	got := header + strings.Join(statements, "\n\n") + "\n"

	if os.Getenv("PARITY_UPDATE") != "" {
		if err := os.WriteFile(schemaFile, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(schemaFile)
	if err != nil {
		t.Fatalf("%v (create it with PARITY_UPDATE=1)", err)
	}
	if string(want) != got {
		t.Errorf("%s is out of date; regenerate it with PARITY_UPDATE=1 go test -tags sqlite_fts5 -run TestParitySchema .\n--- got ---\n%s", paritySchemaPath, got)
	}
}
